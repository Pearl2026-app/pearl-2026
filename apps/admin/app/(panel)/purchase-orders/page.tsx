'use client';
import Link from 'next/link';
import { Suspense, useState } from 'react';
import { Badge, Input, Select } from '@sahyadri/ui';
import { DataTable, Pagination } from '@/components/data-table';
import { useRefOptions } from '@/components/fields';
import { PoEarnings } from '@/components/po-work';
import { qs } from '@/lib/api';
import { PageHeader } from '@/components/shell';
import { PO_STATUSES } from '@/lib/custom';
import { date, humanize, inr } from '@/lib/format';
import { useCan, useMe } from '@/lib/session';
import { useList, useListParams } from '@/lib/use-list';

interface P { id: string; number: string; createdAt: string; dueDate: string; status: string; stage: string | null; autoGenerated: boolean; quantity: number; agreedCostPaise: number; metal: string | null; metalWeightG: string | null; billAmountPaise: number | null; billMismatch: boolean; pearlsSentAt: string | null; pearlsReceivedAt: string | null; cost: { totalPaise: number } | null; paidPaise?: number; balancePaise?: number; manufacturer: { name: string }; product: { id: string; name: string; sku: string } | null; order: { id: string; number: string } | null }
function List() {
  const { params, set } = useListParams();
  const { data, isLoading } = useList<P>('/admin/purchase-orders', params);
  const can = useCan();
  const makers = useRefOptions(can('MANUFACTURERS') ? { path: '/admin/manufacturers' } : undefined);
  const { data: me } = useMe();
  const isMaker = me?.role === 'MANUFACTURER';
  const [q, setQ] = useState(params.q ?? '');
  return (
    <div>
      <PageHeader
        title="Purchase orders"
        actions={
          <>
            <a className="inline-flex min-h-9 items-center rounded-sm border border-line bg-surface px-3 text-sm" href={`/api/v1/admin/purchase-orders${qs({ ...params, format: 'csv', page: undefined, pageSize: undefined })}`}>Export CSV</a>
            {can('PURCHASE_ORDERS', 'create') && <Link href="/purchase-orders/new" className="inline-flex min-h-9 items-center rounded-sm bg-accent px-3 text-sm font-medium text-white">New purchase order</Link>}
          </>
        }
      />
      <form className="mb-3 flex flex-wrap gap-2" onSubmit={(e) => { e.preventDefault(); set({ q }); }}>
        <Input aria-label="Search" placeholder="PO, SR code, metal or notes" value={q} onChange={(e) => setQ(e.target.value)} className="max-w-xs" />
        <Select aria-label="Status" className="max-w-44" value={params.status ?? ''} onChange={(e) => set({ status: e.target.value || undefined })}>
          <option value="">All statuses</option>
          {PO_STATUSES.map((s) => <option key={s} value={s}>{humanize(s)}</option>)}
        </Select>
        {!isMaker && (
          <Select aria-label="Manufacturer" className="max-w-52" value={params.manufacturerId ?? ''} onChange={(e) => set({ manufacturerId: e.target.value || undefined })}>
            <option value="">All manufacturers</option>
            {makers.data?.items.map((m) => <option key={String(m.id)} value={String(m.id)}>{String(m.name)}</option>)}
          </Select>
        )}
      </form>
      {me && (isMaker || can('PURCHASE_ORDERS', 'create')) && <PoEarnings manufacturerId={params.manufacturerId} mine={isMaker} />}
      <DataTable
        rows={data?.items ?? []}
        loading={isLoading}
        rowHref={(r) => `/purchase-orders/${r.id}`}
        empty="No purchase orders"
        columns={[
          { key: 'number', label: 'PO', render: (r) => <>{r.number}{r.autoGenerated ? <span className="ml-1 rounded-sm bg-surface-muted px-1 text-[11px] text-muted">auto</span> : null}</> },
          { key: 'createdAt', label: 'Date', render: (r) => date(r.createdAt) },
          { key: 'manufacturer', label: 'Manufacturer', render: (r) => r.manufacturer.name },
          { key: 'product', label: 'Piece', render: (r) => <>{r.product ? `${r.product.name} (${r.product.sku})` : r.order?.number ?? '—'}{r.metal || r.metalWeightG ? <span className="block text-xs text-muted">{[r.metal, r.metalWeightG ? `${Number(r.metalWeightG)} g` : null, `× ${r.quantity}`].filter(Boolean).join(' · ')}</span> : null}</> },
          { key: 'agreedCostPaise', label: 'Cost', render: (r) => <>{inr(r.agreedCostPaise)}{r.billAmountPaise != null ? <span className="block text-xs">{r.billMismatch ? <Badge tone="danger">Bill {inr(r.billAmountPaise)}</Badge> : <span className="text-muted">Bill {inr(r.billAmountPaise)}</span>}</span> : null}{r.status !== 'DRAFT' && r.paidPaise ? <span className="block text-xs text-muted">{r.balancePaise && r.balancePaise > 0 ? `Paid ${inr(r.paidPaise)} · due ${inr(r.balancePaise)}` : `Paid ${inr(r.paidPaise)}`}</span> : null}</> },
          { key: 'dueDate', label: 'Due', render: (r) => date(r.dueDate) },
          { key: 'status', label: 'Status', render: (r) => <>{humanize(r.status)}<span className="block text-xs text-muted">{r.status === 'SENT' && !r.pearlsReceivedAt ? (r.pearlsSentAt ? 'Pearls on the way' : 'Pearls not sent') : r.stage}</span></> },
        ]}
      />
      {data && <Pagination page={data.page} pageSize={data.pageSize} total={data.total} onPage={(p) => set({ page: String(p) })} />}
    </div>
  );
}

export default function PurchaseOrdersPage() {
  return (
    <Suspense>
      <List />
    </Suspense>
  );
}
