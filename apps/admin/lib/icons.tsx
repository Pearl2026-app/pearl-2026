/** The icon for a page path: the longest menu path it starts with. */
export function iconFor(pathname: string): LucideIcon | null {
  if (pathname === '/' || pathname === '') return PAGE_ICONS['/']!;
  const key = Object.keys(PAGE_ICONS)
    .filter((k) => k !== '/' && (pathname === k || pathname.startsWith(k + '/')))
    .sort((a, b) => b.length - a.length)[0];
  return key ? PAGE_ICONS[key]! : null;
}
